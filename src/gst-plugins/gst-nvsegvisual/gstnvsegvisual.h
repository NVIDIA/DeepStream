/* Standard boilerplate stuff */
#define GST_TYPE_NV_SEG_VISUAL (gst_nvseg_visual_get_type())
#define GST_NV_SEG_VISUAL(obj) (G_TYPE_CHECK_INSTANCE_CAST((obj),GST_TYPE_NV_SEG_VISUAL,GstNvSegVisual))
