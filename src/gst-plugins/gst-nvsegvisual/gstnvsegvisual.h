#define GST_NV_SEG_VISUAL_CAST(obj)  ((GstNvSegVisual *)(obj))

struct _GstNvSegVisual
{
  GstBaseTransform base_trans;

  // Unique ID of the element. The labels generated by the element will be
  // updated at index `unique_id` of attr_info array in NvDsObjectParams.
  guint unique_id;

  // Frame number of the current input buffer
  guint64 frame_num;

  // Input video info (resolution, color format, framerate, etc)
  GstVideoInfo video_info;

  // Resolution at which frames/objects should be processed
  gint output_width;
  gint output_height;

  // GPU ID on which we expect to execute the task
  guint gpu_id;

  // Buffer pool size used for optical flow output
  guint pool_size;

  // Segmentation-Meta id for which segmentation is visualize
  gint operate_on_seg_meta_id;

  gboolean original_background;
  guint class_id;
  float alpha;
  gboolean flag_alloc_dev_memory;
  unsigned char* class2BGR_device;
  cudaStream_t stream;
  gboolean gpu_on;

  int *class_map_device;

  gint batch_size;
  guint num_batch_buffers;

  gint input_feature;
  gint output_feature;
  gint cuda_mem_type;
  GstVideoFormat input_fmt;
  GstVideoFormat output_fmt;

  GstVideoInfo in_info;
  GstVideoInfo out_info;

  GstCaps *sinkcaps;
  GstCaps *srccaps;

  GstBufferPool *pool;
};

// Boiler plate stuff
struct _GstNvSegVisualClass
{
  GstBaseTransformClass parent_class;
};

